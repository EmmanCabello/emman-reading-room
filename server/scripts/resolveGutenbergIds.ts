/**
 * One-off maintenance tool: matches the seed works against the official
 * Project Gutenberg catalogue CSV and rewrites catalog-seed/gutenbergIds.ts.
 *
 *   curl -o pg_catalog.csv https://www.gutenberg.org/cache/epub/feeds/pg_catalog.csv
 *   npx tsx scripts/resolveGutenbergIds.ts pg_catalog.csv
 *
 * Works with no confident match stay unlinked (cards then show a catalogue search link).
 */
import fs from "node:fs";
import path from "node:path";
import { buildSeedWorks } from "../src/data/catalog-seed";

function parseCsv(text: string): string[][] {
  const rows: string[][] = [];
  let row: string[] = [];
  let cell = "";
  let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (quoted) {
      if (ch === '"') {
        if (text[i + 1] === '"') {
          cell += '"';
          i++;
        } else quoted = false;
      } else cell += ch;
    } else if (ch === '"') quoted = true;
    else if (ch === ",") {
      row.push(cell);
      cell = "";
    } else if (ch === "\n") {
      row.push(cell);
      rows.push(row);
      row = [];
      cell = "";
    } else if (ch !== "\r") cell += ch;
  }
  if (cell || row.length) {
    row.push(cell);
    rows.push(row);
  }
  return rows;
}

const flat = (s: string) =>
  s
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/&/g, " and ")
    .replace(/[^a-z0-9 ]+/g, " ")
    .replace(/\s+/g, " ")
    .trim();

const stripArticle = (s: string) => s.replace(/^(the|a|an) /, "");

/** Every plausible short form of a catalogue title. */
function variantsOf(title: string): string[] {
  const cleaned = title.replace(/\s+/g, " ");
  const out = new Set<string>();
  out.add(stripArticle(flat(cleaned)));
  for (const part of cleaned.split(/[;:]/)) out.add(stripArticle(flat(part)));
  out.add(stripArticle(flat(cleaned.split(/\s+or,?\s+/i)[0])));
  out.add(stripArticle(flat(cleaned.split(",")[0])));
  out.add(stripArticle(flat(cleaned.split(/[;:,]/)[0])));
  out.delete("");
  return [...out];
}

const ALIASES: Record<string, string[]> = {
  Laozi: ["laozi", "lao tzu", "laotse", "lao tze"],
  "Sun Tzu": ["sunzi", "sun tzu", "sun wu"],
  "Saint Augustine": ["augustine"],
  "Meriwether Lewis and William Clark": ["lewis", "clark"],
  "Alexander Hamilton, James Madison and John Jay": ["hamilton", "madison", "jay"]
};

function surnames(author: string): string[] {
  if (ALIASES[author]) return ALIASES[author];
  const cleaned = author.replace(/\b(jr|sr)\.?$/i, "").trim();
  return [flat(cleaned).split(" ").pop() ?? ""];
}

const csvPath = process.argv[2];
if (!csvPath) throw new Error("usage: tsx scripts/resolveGutenbergIds.ts <pg_catalog.csv>");
const rows = parseCsv(fs.readFileSync(csvPath, "utf8")).slice(1);

interface Entry { id: number; title: string; variants: string[]; authors: string }
const catalogue: Entry[] = [];
for (const r of rows) {
  if (r.length < 6) continue;
  const [id, type, , title, lang, authors] = r;
  if (type !== "Text" || !/^en\b/.test(lang)) continue;
  catalogue.push({ id: Number(id), title: title.replace(/\s+/g, " "), variants: variantsOf(title), authors: flat(authors) });
}

const resolved: Record<string, number> = {};
const missing: string[] = [];
for (const work of buildSeedWorks()) {
  const wantedSet = new Set<string>([
    stripArticle(flat(work.title)),
    stripArticle(flat(work.title.split(";")[0]))
  ]);
  const wanted = [...wantedSet];
  const names = surnames(work.author);
  const pool = catalogue.filter((c) => names.some((n) => c.authors.includes(n)));
  const exact = pool.filter((c) => c.variants.some((v) => wanted.includes(v)));
  const prefix = pool.filter((c) =>
    c.variants.some((v) => wanted.some((w) => v.startsWith(w + " ") && w.length >= v.length * 0.3))
  );
  const pick = (exact.length ? exact : prefix).sort((a, b) => a.id - b.id)[0];
  if (pick) {
    resolved[work.slug] = pick.id;
    console.log(`OK   ${work.title} / ${work.author} -> ${pick.id} (${pick.title})`);
  } else {
    missing.push(`${work.title} / ${work.author}`);
  }
}

const body = Object.keys(resolved)
  .sort()
  .map((k) => `  "${k}": ${resolved[k]}`)
  .join(",\n");
const target = path.join(__dirname, "..", "src", "data", "catalog-seed", "gutenbergIds.ts");
fs.writeFileSync(
  target,
  `/** Generated by scripts/resolveGutenbergIds.ts from the Project Gutenberg catalogue. */\nexport const gutenbergIds: Record<string, number> = {\n${body}\n};\n`
);
console.log(`\nResolved ${Object.keys(resolved).length}, unresolved ${missing.length}`);
for (const m of missing) console.log(`MISS ${m}`);
